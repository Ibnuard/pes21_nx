"""Compare owned FL26 and Mobile referee motion inputs without changing them.

Only hashes, sizes and format metadata are reported. No animation payload,
executable code, actor or runtime package is generated by this audit.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct

try:
    from .build_fl26_cup_catalog import cpk_member, index_cpk
    from .convert_ef_referee import CLIPS, read_skeleton, unpack_wesys
except ImportError:
    from build_fl26_cup_catalog import cpk_member, index_cpk
    from convert_ef_referee import CLIPS, read_skeleton, unpack_wesys


BODY = "common/anime/FoxAnim/Body/"
SKELETONS = ("body_anim_skel.ask", "body_render_skel.ask", "body_skel.frig")
# Full Fox string identities, checked against the compatible Mobile library.
# These identify data records; no game executable instructions are included.
CLIP_KEYS = {
    "referee_stand_0": 0xDD60303592B7,
    "walk_1_1": 0x36033BB0CA6B,
    "run_2_2": 0xC63628739FA0,
    "run_3_3": 0x3A013F6777D0,
    "referee_stand_0_whistle": 0x4432906E57BC,
    "referee_hand_up_0": 0x3CCD1753BFEA,
    "referee_1_0_000_hand_middle_point_000": 0x766B9324DF0B,
    "referee_hand_up_0_hand_down": 0x1BD3AC3CF101,
}
MEMBER_LIMIT = 64 * 1024 * 1024


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def gani_metadata(data: bytes) -> dict:
    if len(data) < 164 or struct.unpack_from("<III", data) != (201106130, 32, len(data)):
        raise ValueError("unsupported or truncated GANI header")
    frames, scale = struct.unpack_from("<Ib", data, 156)
    if not 2 <= frames <= 600 or scale != 10:
        raise ValueError("unsupported referee motion timing")
    return {"bytes": len(data), "sha256": digest(data),
            "frames": frames, "frame_scale": scale}


def inspect_mtar(data: bytes, requested: dict[int, str]) -> dict[str, dict]:
    if len(data) < 32 or len(data) > MEMBER_LIMIT:
        raise ValueError("invalid MTAR size")
    magic, count = struct.unpack_from("<II", data)
    table_end = 32 + count * 16
    if magic != 0x0BFFA89C or not 0 < count <= 100000 or table_end > len(data):
        raise ValueError("unsupported or truncated MTAR index")
    found = {}
    for i in range(count):
        key, offset, size = struct.unpack_from("<QII", data, 32 + i * 16)
        if offset < table_end or not size or size > len(data) - offset:
            raise ValueError("MTAR clip outside payload bounds")
        name = requested.get(key)
        if name is None:
            continue
        if name in found:
            raise ValueError("duplicate requested motion identity")
        found[name] = {"key": f"0x{key:012x}",
                       **gani_metadata(data[offset:offset + size])}
    return found


def inspect_bank(path: Path) -> dict:
    index, base = index_cpk(path)
    requested = {key: name for name, key in CLIP_KEYS.items()}

    def read(name: str) -> bytes:
        row = index.get(name)
        if row is None:
            raise ValueError(f"missing referee bank member: {name}")
        if not 0 < int(row["FileSize"]) <= MEMBER_LIMIT:
            raise ValueError("referee bank member exceeds audit bound")
        raw = unpack_wesys(cpk_member(path, index, base, name))
        if not 0 < len(raw) <= MEMBER_LIMIT:
            raise ValueError("decoded referee bank member exceeds audit bound")
        return raw

    skeletons = {}
    for name in SKELETONS:
        data = read(BODY + "CharacterAssets/" + name)
        entry = {"bytes": len(data), "sha256": digest(data)}
        if name.endswith(".ask"):
            entry["bones"] = len(read_skeleton(data))
        skeletons[name] = entry
    archives, clips = {}, {}
    for number in range(10):
        name = f"body_anime_file{number}.mtar"
        data = read(BODY + name)
        archives[name] = {"bytes": len(data), "sha256": digest(data)}
        for motion, entry in inspect_mtar(data, requested).items():
            if motion in clips:
                raise ValueError("motion identity duplicated across archives")
            clips[motion] = {"archive": name, **entry}
    if set(clips) != set(CLIPS):
        raise ValueError("missing referee motions: " + ", ".join(sorted(set(CLIPS) - set(clips))))
    return {"path": str(path.resolve()), "members": len(index),
            "skeletons": skeletons, "archives": archives, "clips": clips}


def compare(fl26_cpk: Path, mobile_cpk: Path) -> dict:
    fl26, mobile = inspect_bank(fl26_cpk), inspect_bank(mobile_cpk)
    equal = {group: all(fl26[group][name] == mobile[group].get(name)
                        for name in fl26[group])
             for group in ("skeletons", "archives", "clips")}
    return {"schema_version": 1, "scope": "read-only referee animation asset audit",
            "fl26": fl26, "mobile": mobile, "equal": equal,
            "full_body_bank_import_redundant": all(equal.values()),
            "limitations": ["Asset equality does not establish executable AI compatibility.",
                            "No match, render, animation sampling or performance test is run."]}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fl26-cpk", type=Path, required=True)
    parser.add_argument("--mobile-cpk", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    report = compare(args.fl26_cpk, args.mobile_cpk)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"equal": report["equal"], "report": str(args.output)}, indent=2))


if __name__ == "__main__":
    main()
